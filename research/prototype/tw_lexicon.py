# --- 簡體偵測：用 OpenCC 逐字判定，不用手工字表 ---
import opencc as _oc
_T2S = _oc.OpenCC('t2s')
_S2T = _oc.OpenCC('s2t')
_CJK = re.compile(r'[一-鿿]')
_cache = {}

# 🔴 2026-09-29 修正：上面那條規則會把「台灣現代標準用字」誤判成簡體。
# OpenCC 的 s2t 走的是「嚴式正體」，會把 台→臺、群→羣、峰→峯，
# 但這三個在台灣的書面標準裡就是正確寫法（台灣、一台車、客群、峰值）。
# 實測：拿這條規則掃一份正常的繁中文件，「台」一個字就誤報 16 次。
# 「干」則是因為它同時是「幹」的簡化字與「干擾／若干」的本字，後者在技術文件裡很常見。
_TW_STANDARD_OK = set("台群峰干")
# ⚠️ 刻意不放行的模稜兩可字：
#   余（姓氏／古語「我」，但也是「餘」的簡化字）
#   于（姓氏，但也是「於」的簡化字）
#   → 在車用語料裡它們出現時幾乎都是簡體汙染，保持攔截。

def is_simplified_char(c: str) -> bool:
    """簡體專有字 = 轉簡後不變、且轉繁後會變，且不在台灣標準用字白名單內。"""
    if c in _cache:
        return _cache[c]
    if c in _TW_STANDARD_OK:
        _cache[c] = False
        return False
    r = _T2S.convert(c) == c and _S2T.convert(c) != c
    _cache[c] = r
    return r

def check(text: str):
    """回傳 (是否合格, 違規清單[(類別, 命中, 建議)])。"""
    bad = []
    for w, tw in MAINLAND_TO_TW.items():
        if w in text:
            bad.append(("大陸用語", w, tw))
    seen = set()
    for c in text:
        if _CJK.match(c) and c not in seen and is_simplified_char(c):
            seen.add(c)
            bad.append(("簡體字", c, _S2T.convert(c)))
    for w in AI_TONE:
        if w in text:
            bad.append(("AI腔", w, ""))
    return (len(bad) == 0), bad

